/**
 * 分析姓名
 * @param {string} fullName - 完整姓名（姓+名），如 '张伟' 或 '欧阳娜娜'
 * @returns {object} 包含五格数理、三才配置、五行分析、总评
 */
export function analyzeName(fullName) {
  const trimmed = fullName.trim();
  if (!trimmed || trimmed.length < 2) {
    return { error: '姓名不能为空或少于2个字符' };
  }

  const chars = [...trimmed];

  // 识别复姓（常见复姓列表）
  const COMPOUND_SURNAMES = [
    '欧阳', '太史', '端木', '上官', '司马', '东方', '独孤', '南宫',
    '万俟', '闻人', '夏侯', '诸葛', '尉迟', '公羊', '赫连', '澹台',
    '皇甫', '宗政', '濮阳', '公冶', '太叔', '申屠', '公孙', '慕容',
    '仲孙', '钟离', '长孙', '宇文', '司徒', '鲜于', '司空', '闾丘',
    '子车', '亓官', '司寇', '巫马', '公西', '漆雕', '乐正', '壤驷',
    '公良', '拓跋', '夹谷', '宰父', '谷梁', '段干', '百里', '呼延',
    '东郭', '南门', '羊舌', '微生', '梁丘', '左丘', '东门', '西门',
    '南宫', '第五', '公仪', '公乘', '太史', '即墨'
  ];

  let surname, givenName, isCompound = false;
  for (const cs of COMPOUND_SURNAMES) {
    if (trimmed.startsWith(cs) && trimmed.length > cs.length) {
      surname = cs;
      givenName = trimmed.slice(cs.length);
      isCompound = true;
      break;
    }
  }
  if (!surname) {
    surname = chars[0];
    givenName = chars.slice(1).join('');
  }

  if (!givenName || givenName.length === 0) {
    return { error: '请提供完整的姓名（姓+名）' };
  }

  // 检测未收录字
  const allChars = [...surname, ...givenName];
  const unknownChars = allChars.filter(ch => !(ch in STROKE_MAP));
  if (unknownChars.length > 0) {
    return {
      warning: `以下字符未收录，笔画数设为0：【待核实】：${unknownChars.join('、')}`,
      unknownChars
    };
  }

  // 计算五格
  const tianGe = calcTianGe(surname, isCompound);
  const renGe = calcRenGe(surname, givenName);
  const diGe = calcDiGe(givenName);
  const zongGe = calcZongGe(surname, givenName);
  const waiGe = calcWaiGe(zongGe, renGe, givenName);

  // 五格数理
  const geShuLi = {
    天格: { value: tianGe, ...(SHULI_81[tianGe] || { text: '【待核实】', luck: '未知', meaning: '' }) },
    人格: { value: renGe, ...(SHULI_81[renGe] || { text: '【待核实】', luck: '未知', meaning: '' }) },
    地格: { value: diGe, ...(SHULI_81[diGe] || { text: '【待核实】', luck: '未知', meaning: '' }) },
    外格: { value: waiGe, ...(SHULI_81[waiGe] || { text: '【待核实】', luck: '未知', meaning: '' }) },
    总格: { value: zongGe, ...(SHULI_81[zongGe] || { text: '【待核实】', luck: '未知', meaning: '' }) }
  };

  // 三才配置
  const tianWx = getWuxingByDigit(tianGe);
  const renWx = getWuxingByDigit(renGe);
  const diWx = getWuxingByDigit(diGe);
  const sancaiKey = `${tianWx.wuxing}${renWx.wuxing}${diWx.wuxing}`;
  const sancaiInfo = SANCAI_RELATIONS[sancaiKey] || { luck: '【待核实】', text: '此三才配置暂无记录' };

  // 五行分布
  const wuxingDistribution = {
    天格: tianWx,
    人格: renWx,
    地格: diWx,
    外格: getWuxingByDigit(waiGe),
    总格: getWuxingByDigit(zongGe)
  };

  // 评分
  const scoreMap = { '大吉': 100, '吉': 70, '凶': 30, '大凶': 10, '未知': 50 };
  const geScores = Object.values(geShuLi).map(v => scoreMap[v.luck] || 50);
  const avgScore = geScores.reduce((a, b) => a + b, 0) / geScores.length;

  // 总评
  const overallLuck = avgScore >= 80 ? '大吉' : avgScore >= 60 ? '吉' : avgScore >= 35 ? '中平' : '凶';

  return {
    fullName: trimmed,
    surname,
    isCompoundSurname: isCompound,
    givenName,
    strokes: {
      surname: [...surname].map(ch => ({ char: ch, stroke: STROKE_MAP[ch] || 0 })),
      givenName: [...givenName].map(ch => ({ char: ch, stroke: STROKE_MAP[ch] || 0 }))
    },
    wuge: geShuLi,
    sancai: {
      key: sancaiKey,
      config: `天格(${tianWx.wuxing}${tianWx.yinYang})·人格(${renWx.wuxing}${renWx.yinYang})·地格(${diWx.wuxing}${diWx.yinYang})`,
      ...sancaiInfo
    },
    wuxingDistribution,
    score: Math.round(avgScore),
    overall: overallLuck,
    summary: `姓名"${trimmed}"五格配置：天格${tianGe}、人格${renGe}、地格${diGe}、外格${waiGe}、总格${zongGe}。三才配置为"${sancaiKey}"（${sancaiInfo.luck}）。总体评分：${Math.round(avgScore)}分（${overallLuck}）。`
  };
}

/**
 * 查找81数理的吉凶
 * @param {number} num - 1-81
 * @returns {object}
 */
export function getShuLi(num) {
  if (num > 81) {
    // 超过81则取余数或按81计（部分版本算法不同）
    num = ((num - 1) % 81) + 1;
  }
  return SHULI_81[num] || { text: '【待核实】', luck: '未知', meaning: '此数暂无记载' };
}

/**
 * 获取三才配置
 * @param {number} tianGe - 天格数
 * @param {number} renGe - 人格数
 * @param {number} diGe - 地格数
 * @returns {object}
 */
export function getSancai(tianGe, renGe, diGe) {
  const twx = getWuxingByDigit(tianGe).wuxing;
  const rwx = getWuxingByDigit(renGe).wuxing;
  const dwx = getWuxingByDigit(diGe).wuxing;
  const key = `${twx}${rwx}${dwx}`;
  return {
    key,
    ...(SANCAI_RELATIONS[key] || { luck: '【待核实】', text: '此三才配置暂无记录' })
  };
}

