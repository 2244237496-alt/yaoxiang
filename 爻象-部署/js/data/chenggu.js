// ==================== 工具函数 ====================

/**
 * 将两.钱格式的数字转换为钱数（1两=10钱）
 * @param {number} liangQian - 如 1.2 表示一两二钱
 * @returns {number} 总钱数
 */
export function toQian(liangQian) {
  return Math.floor(liangQian) * 10 + Math.round((liangQian % 1) * 10);
}

/**
 * 将总钱数转换为两.钱格式
 * @param {number} totalQian - 总钱数
 * @returns {number} 两.钱格式
 */
export function toLiangQian(totalQian) {
  return Math.floor(totalQian / 10) + (totalQian % 10) / 10;
}
