export function getShiShen(riGan, otherGan) {
  const riIdx = TIAN_GAN.indexOf(riGan);
  const riYY = TIAN_GAN_YINYANG[riGan];
  const oYY = TIAN_GAN_YINYANG[otherGan];
  const riWx = TIAN_GAN_WUXING[riGan];
  const oWx = TIAN_GAN_WUXING[otherGan];

  if(riWx === oWx) return riYY === oYY ? '比肩' : '劫财';
  if(WU_XING_SHENG[oWx] === riWx) return oYY === riYY ? '偏印' : '正印';
  if(WU_XING_SHENG[riWx] === oWx) return riYY === oYY ? '食神' : '伤官';
  if(WU_XING_KE[oWx] === riWx) return oYY === riYY ? '七杀' : '正官';
  if(WU_XING_KE[riWx] === oWx) return riYY === oYY ? '偏财' : '正财';
  return '未知';
}
